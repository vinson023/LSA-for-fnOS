  function replaceDirectText(node) {
    var original = node.nodeValue;
    var label = original.replace(/\s+/g, " ").trim();
    if (Object.prototype.hasOwnProperty.call(directText, label)) {
      if (directText[label] !== label) node.nodeValue = original.replace(label, directText[label]);
      return;
    }

    // These values are assembled directly by the compiled GWT views.
    // Keep the percentage untouched while translating the visible unit.
    var chargeMatch = original.match(/^(\s*)(\d+(?:\.\d+)?%) Charge(\s*)$/);
    if (chargeMatch) {
      node.nodeValue = chargeMatch[1] + chargeMatch[2] + " 电量" + chargeMatch[3];
      return;
    }

    if (label === "Unconfigured Drives") {
      node.nodeValue = original.replace(label, "未配置的磁盘");
    }
  }

  function translateTree(root) {
    if (!root || root.nodeType !== 1) return;
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    var node;
    while ((node = walker.nextNode())) replaceDirectText(node);
  }

